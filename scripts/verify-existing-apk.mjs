import assert from 'node:assert/strict';
import { readFileSync, appendFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const meta=JSON.parse(readFileSync('artifacts/build/metadata.json','utf8'));
const source=JSON.parse(readFileSync('artifacts/source-run.json','utf8'));
const jobs=JSON.parse(readFileSync('artifacts/source-jobs.json','utf8')).jobs;
assert.equal(source.path,'.github/workflows/offline-phone-preview.yml');
assert.equal(String(source.id),process.env.SOURCE_RUN);
assert.equal(meta.workflowRun,process.env.SOURCE_RUN);
assert.equal(meta.commit,source.head_sha);
assert(jobs.some(j=>j.name==='Build the exact APKs once'&&j.conclusion==='success'));
const version=String(source.run_number);
assert(/^\d+$/.test(version)&&/^[a-f0-9]{40}$/.test(meta.commit));
assert.equal(meta.apk,Number(version)>=35?`tia-stable-${version}.apk`:`Hamrah-stable-${version}.apk`);
assert.equal(meta.packageId,`ir.wealthos.personalagent.stable${version}`);
assert.equal(createHash('sha256').update(readFileSync(`artifacts/build/${meta.apk}`)).digest('hex'),meta.sha256);
const env=`APK_FILE=${meta.apk}\nAPK_PACKAGE=${meta.packageId}\nAPK_VERSION=${version}\nAPK_COMMIT=${meta.commit}\n`;
writeFileSync('artifacts/apk-identity.env',env);
if(process.env.GITHUB_ENV)appendFileSync(process.env.GITHUB_ENV,env);
console.log(`Verified unchanged APK ${version}: ${meta.sha256}`);
