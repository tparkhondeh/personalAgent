// Synthetic fixtures only. The public test passphrase below must never protect real data.
import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, readdir, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { createClient } from "@libsql/client";
import { runPrivateBackup } from "./private-backup.mjs";
await mkdir("backups/local", { recursive: true });
const dir = await mkdtemp(path.resolve("backups/local/qa-private-"));
const secretDir = await mkdtemp(path.join(os.tmpdir(), "tia-synthetic-secret-"));
const secretFile = path.join(secretDir, "synthetic.txt");
const wrongSecretFile = path.join(secretDir, "wrong-synthetic.txt");
await writeFile(secretFile, "PUBLIC-SYNTHETIC-TEST-ONLY-NOT-A-REAL-KEY", { flag: "wx", mode: 0o600 });
await writeFile(wrongSecretFile, "OTHER-PUBLIC-SYNTHETIC-TEST-ONLY-NOT-A-REAL-KEY", { flag: "wx", mode: 0o600 });
const source = path.join(dir, "fixture.db");
const sql = createClient({ url: pathToFileURL(source).href });
await sql.executeMultiple("CREATE TABLE Fixture(id TEXT PRIMARY KEY, done INTEGER); INSERT INTO Fixture VALUES('synthetic-task',1);");
sql.close();
await writeFile(source + ".json", JSON.stringify({ integrity: "ok", syntheticOnly: true }), { flag: "wx" });
const original = await readFile(source);
const encrypted = await runPrivateBackup("seal", source, secretFile);
assert(encrypted.verified && !encrypted.uploaded);
assert(!(await readFile(encrypted.output)).includes(Buffer.from("synthetic-task")));
const beforeFailure = await readdir("backups/local");
await assert.rejects(runPrivateBackup("restore", encrypted.output, wrongSecretFile));
assert.deepEqual(await readdir("backups/local"), beforeFailure);
const restored = await runPrivateBackup("restore", encrypted.output, secretFile);
assert((await readFile(restored.output)).equals(original));
assert((await readFile(source)).equals(original));
assert(!restored.liveDatabaseChanged && !restored.schedulersStarted);
const again = await runPrivateBackup("seal", source, secretFile);
assert.notEqual(again.output, encrypted.output);
assert.notEqual(again.sha256, encrypted.sha256);
await assert.rejects(runPrivateBackup("seal", "prisma/schema.prisma", secretFile));
await assert.rejects(runPrivateBackup("seal", source, "package.json"));
await assert.rejects(runPrivateBackup("restore", source, secretFile));
console.log(JSON.stringify({ passed: true, syntheticOnly: true, encryptedRoundTrip: true, wrongSecretWritesNothing: true, sourcePreserved: true, previousBackupsPreserved: true, restoredSha256: restored.sha256, fixtures: dir, externalUpload: false, realKeyCreated: false }));
