// Authenticated staging smoke; a fixed public FLEURS file only, never owner audio.
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const base=process.env.QA_BASE_URL||'https://personalagent.wealthos.ir:8443';
if(base!=='https://personalagent.wealthos.ir:8443'&&!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(base))throw Error('Only local/approved staging');
const root='artifacts/speech-poems/benchmark';
const manifest=JSON.parse(await readFile(`${root}/manifest.json`,'utf8')),item=manifest.samples[0];
const source=await readFile(`${root}/${item.file}`);
assert.equal(createHash('sha256').update(source).digest('hex'),item.sha256);
let samples,format;
for(let p=12;p+8<=source.length;){const key=source.toString('ascii',p,p+4),length=source.readUInt32LE(p+4);assert(p+8+length<=source.length);if(key==='fmt ')format=[source.readUInt16LE(p+8),source.readUInt16LE(p+10),source.readUInt32LE(p+12),source.readUInt16LE(p+22)];if(key==='data')samples=source.subarray(p+8,p+8+length);p+=8+length+length%2;}
assert.deepEqual(format,[3,1,16000,32]);assert(samples);
const audio=Buffer.alloc(44+samples.length/2);
audio.write('RIFF');audio.writeUInt32LE(audio.length-8,4);audio.write('WAVEfmt ',8);audio.writeUInt32LE(16,16);audio.writeUInt16LE(1,20);audio.writeUInt16LE(1,22);audio.writeUInt32LE(16000,24);audio.writeUInt32LE(32000,28);audio.writeUInt16LE(2,32);audio.writeUInt16LE(16,34);audio.write('data',36);audio.writeUInt32LE(audio.length-44,40);
for(let i=0;i<samples.length/4;i++)audio.writeInt16LE(Math.trunc(Math.max(-1,Math.min(1,samples.readFloatLE(i*4)))*32767),44+i*2);
const stamp=Date.now();
const auth=await fetch(base+'/api/auth/sign-up/email',{method:'POST',headers:{origin:base,'Content-Type':'application/json'},body:JSON.stringify({email:`voice-public-qa-${stamp}@example.invalid`,name:'آزمون صدای عمومی',password:`Synthetic-public-voice-${stamp}`})});
assert.equal(auth.status,200,'Synthetic login');
const cookie=auth.headers.getSetCookie().map(v=>v.split(';')[0]).join('; ');
const headers={origin:base,cookie,'Content-Type':'audio/wav','x-audio-consent':'tia-server'};
const endpoint=base+'/api/agent/local-transcribe';
const get=path=>fetch(base+path,{headers:{cookie}}).then(r=>r.json());
let checks=0;
assert.equal((await fetch(endpoint)).status,401);checks++;
assert.equal((await get('/api/agent/local-transcribe')).data.enabled,true);checks++;
assert.equal((await fetch(endpoint,{method:'POST',headers:{...headers,'x-audio-consent':''},body:audio})).status,422);checks++;
assert.equal((await fetch(endpoint,{method:'POST',headers:{...headers,origin:'https://invalid.example'},body:audio})).status,403);checks++;
assert.equal((await fetch(endpoint,{method:'POST',headers,body:'invalid'})).status,422);checks++;
const before={tasks:(await get('/api/tasks')).data.length,meetings:(await get('/api/meetings')).data.length};
const start=performance.now(),response=await fetch(endpoint,{method:'POST',headers,body:audio});
assert.equal(response.status,200,'Actual own-server transcription');
const result=await response.json(),elapsedMs=performance.now()-start;
const expected=JSON.parse(await readFile(`${root}/shenava-server.json`,'utf8')).results[0].text.trim();
assert.equal(result.data.text,expected);checks++;
assert.deepEqual({tasks:(await get('/api/tasks')).data.length,meetings:(await get('/api/meetings')).data.length},before);checks++;
const draft=await fetch(base+'/api/agent',{method:'POST',headers:{origin:base,cookie,'Content-Type':'application/json'},body:JSON.stringify({message:result.data.text,localOnly:true})});
assert.equal(draft.status,200);checks++;
assert.deepEqual({tasks:(await get('/api/tasks')).data.length,meetings:(await get('/api/meetings')).data.length},before);checks++;
const report={passed:true,checks,target:base,publicFixture:item.id,expectedTextMatched:true,elapsedMs,noTaskOrMeetingBeforeApproval:true,privateAudioUsed:false};
await writeFile(`artifacts/speech-poems/voice-api-${stamp}.json`,JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
